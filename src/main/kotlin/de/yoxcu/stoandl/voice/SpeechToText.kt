/** Speech to transcribe: mono 16-bit PCM, or an encoded clip a backend may take as it is (a voice note). */
sealed interface SttAudio {
    class Pcm16(val samples: ShortArray, val sampleRate: Int) : SttAudio
    class Clip(val file: File, val mime: String) : SttAudio
}

/** What a backend made of the audio. */
sealed interface SttOutcome {
    /** The transcript; blank when nothing was said. */
    data class Text(val text: String) : SttOutcome
    /** The service couldn't be reached (the watch shows "No internet connection"). */
    data class Unreachable(val message: String) : SttOutcome
    /** The engine failed, timed out or said something unusable. */
    data class Failed(val message: String) : SttOutcome
}

/**
 * A speech-to-text engine. One interface for every consumer (the watch's dictation, D-Bus `Transcribe`,
 * an extension's `transcribe`), chosen in one place ([VoiceBackends]).
 */
interface SpeechToText {
    /** `command` | `http`. */
    val id: String
    /** Null when ready to use, else why not (cheap: no network, no model load). */
    fun readiness(): String?
    suspend fun transcribe(audio: SttAudio, language: String, timeoutMs: Long): SttOutcome
}

/** The engine's `{lang}`: an ISO-639 code or `auto`. Anything else becomes `auto`. */
internal fun safeLanguage(lang: String): String = lang.trim().lowercase().takeIf { it.matches(Regex("[a-z]{2,3}")) } ?: "auto"

/** Subtitle credits Whisper invents on silence (its training data was subtitles), dropped when they are the
 *  whole output. */
private val SILENCE_HALLUCINATIONS = listOf(
    Regex("""(?i)^untertitel (der|von|im auftrag).*"""),
    // Not "Thank you." / "Vielen Dank.": those are real replies too.
    Regex("""(?i)^(sous-titres|subtitles) (réalisés|by).*"""),
)

/** Engine output as one line of text: lines joined, whitespace collapsed, whisper's `[BLANK_AUDIO]`-style
 *  markers and silence hallucinations dropped. */
internal fun normalizeTranscript(raw: String): String {
    val text = raw.replace(Regex("""\[[A-Z_ ]+]|\([a-z ]+\)"""), " ").replace(Regex("""\s+"""), " ").trim()
    return if (SILENCE_HALLUCINATIONS.any { it.matches(text) }) "" else text
}

/**
 * A local engine run as a command (whisper.cpp's `whisper-cli`, `parakeet-cli`, a script around Vosk or
 * sherpa-onnx): [template] is a shell command line with `{wav}` (a 16 kHz mono WAV) and `{lang}` filled
 * in, printing the transcript on stdout. Both substitutions are generated by the daemon and contain no
 * shell metacharacters. The child is killed at the deadline.
 */
class CommandStt(private val template: String) : SpeechToText {
    override val id = "command"

    override fun readiness(): String? {
        if (template.isBlank()) return "voice.command is empty"
        return missingProgram(template)?.let { "'$it' not found" }
    }

    override suspend fun transcribe(audio: SttAudio, language: String, timeoutMs: Long): SttOutcome = withContext(Dispatchers.IO) {
        val wav = when (audio) {
            is SttAudio.Pcm16 -> Wav.encode(Wav.resample(audio.samples, audio.sampleRate, 16_000), 16_000)
            is SttAudio.Clip -> clipToWav(audio) ?: return@withContext SttOutcome.Failed("can't decode ${audio.mime} for a local engine")
        }
        val file = File(CacheDirs.dir("voice"), "${UUID.randomUUID()}.wav")
        try {
            file.writeBytes(wav)
            file.setReadable(false, false); file.setReadable(true, true)
            val cmd = template.replace("{wav}", file.absolutePath).replace("{lang}", safeLanguage(language))
            val r = runProcess(listOf("sh", "-c", cmd), timeoutMs)
                ?: return@withContext SttOutcome.Failed("can't start the voice command")
            when {
                r.timedOut -> SttOutcome.Failed("voice command took longer than ${timeoutMs / 1000} s")
                r.exitCode != 0 -> SttOutcome.Failed("voice command exited ${r.exitCode}: ${r.stderr.trim().takeLast(300)}")
                // parakeet-cli exits 0 on failure: empty output with an error on stderr is a failure.
                r.stdout.isBlank() && r.stderr.contains(Regex("(?i)error|fail")) ->
                    SttOutcome.Failed("voice command printed nothing: ${r.stderr.trim().takeLast(300)}")
                else -> SttOutcome.Text(normalizeTranscript(r.stdout))
            }
        } finally {
            file.delete()
        }
    }

    private fun clipToWav(clip: SttAudio.Clip): ByteArray? = when {
        clip.mime.contains("wav") -> clip.file.readBytes()
        clip.mime.contains("ogg") || clip.mime.contains("opus") ->
            OggOpus.decode(clip.file.readBytes())?.let { (pcm, rate) -> Wav.encode(Wav.resample(pcm, rate, 16_000), 16_000) }
        else -> null
    }
}

/**
 * An OpenAI-compatible transcription endpoint (`POST …/v1/audio/transcriptions`, multipart `file`): a
 * self-hosted whisper.cpp `whisper-server`, speaches, LocalAI, or a hosted service with [apiKey]. Network
 * egress, so only used when the user chose it (`voice.backend = http`).
 */
class HttpStt(
    private val client: HttpClient,
    private val url: String,
    private val model: String,
    private val apiKey: String?,
) : SpeechToText {
    override val id = "http"

    override fun readiness(): String? =
        if (url.startsWith("http://") || url.startsWith("https://")) null else "voice.url is not set"

    override suspend fun transcribe(audio: SttAudio, language: String, timeoutMs: Long): SttOutcome {
        val (bytes, name, mime) = when (audio) {
            is SttAudio.Pcm16 -> Triple(Wav.encode(Wav.resample(audio.samples, audio.sampleRate, 16_000), 16_000), "audio.wav", "audio/wav")
            is SttAudio.Clip -> Triple(audio.file.readBytes(), audio.file.name, audio.mime)
        }
        val lang = safeLanguage(language)
        return try {
            val response = client.submitFormWithBinaryData(
                url = url,
                formData = formData {
                    append("file", bytes, Headers.build {
                        append(HttpHeaders.ContentType, mime)
                        append(HttpHeaders.ContentDisposition, "filename=\"$name\"")
                    })
                    if (model.isNotBlank()) append("model", model)
                    if (lang != "auto") append("language", lang)
                    append("response_format", "json")
                },
            ) {
                timeout { requestTimeoutMillis = timeoutMs }
                if (!apiKey.isNullOrBlank()) header(HttpHeaders.Authorization, "Bearer $apiKey")
            }
            val body = response.bodyAsText()
            if (!response.status.isSuccess()) return SttOutcome.Failed("HTTP ${response.status.value}: ${body.take(200)}")
            val text = runCatching { Json.parseToJsonElement(body).jsonObject["text"]?.jsonPrimitive?.content }.getOrNull() ?: body
            SttOutcome.Text(normalizeTranscript(text))
        } catch (e: IOException) {
            SttOutcome.Unreachable(e.message ?: "unreachable")
        } catch (e: Exception) {
            if (e.javaClass.simpleName.contains("Timeout")) SttOutcome.Failed("no answer within ${timeoutMs / 1000} s")
            else SttOutcome.Unreachable(e.message ?: e.javaClass.simpleName)
        }
    }
}
